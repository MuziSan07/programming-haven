"""Book storage and metadata extraction for uploaded PDF and EPUB files."""

import posixpath
import secrets
import zipfile
from pathlib import Path
from xml.etree import ElementTree

from fastapi import UploadFile
from pypdf import PdfReader

from ..config import get_settings

CHUNK = 1024 * 1024
MAX_COVER = 5 * 1024 * 1024
MAX_XML = 2 * 1024 * 1024  # container.xml / OPF files are tiny; anything bigger is suspicious
COVER_TYPES = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp", "image/gif": "gif"}
COVER_MAGIC = [(b"\xff\xd8\xff", "jpg"), (b"\x89PNG\r\n\x1a\n", "png"), (b"RIFF", "webp"), (b"GIF8", "gif")]
NS = {"c": "urn:oasis:names:tc:opendocument:xmlns:container", "opf": "http://www.idpf.org/2007/opf",
      "dc": "http://purl.org/dc/elements/1.1/"}


class BookError(Exception):
    def __init__(self, message: str, status: int = 400):
        super().__init__(message)
        self.message, self.status = message, status


def storage() -> Path:
    path = Path(get_settings().books_dir)
    path.mkdir(parents=True, exist_ok=True)
    return path


def path_for(name: str) -> Path:
    # Stored names are generated by us, but never let one escape the books directory
    return storage() / Path(name).name


def remove(name: str | None) -> None:
    if name:
        path_for(name).unlink(missing_ok=True)


async def save_upload(upload: UploadFile) -> tuple[str, int]:
    """Stream an upload to disk under a random name, enforcing the size limit. Returns (name, size)."""
    limit = get_settings().max_book_mb * 1024 * 1024
    name = f"{secrets.token_hex(12)}.upload"
    path = path_for(name)
    size = 0
    try:
        with path.open("wb") as out:
            while chunk := await upload.read(CHUNK):
                size += len(chunk)
                if size > limit:
                    raise BookError(f"The file is larger than {get_settings().max_book_mb} MB", 413)
                out.write(chunk)
    except BaseException:
        path.unlink(missing_ok=True)
        raise
    if size == 0:
        path.unlink(missing_ok=True)
        raise BookError("The file is empty")
    return name, size


def detect_format(path: Path) -> str:
    with path.open("rb") as f:
        head = f.read(1024)
    if b"%PDF-" in head:
        return "pdf"
    if head.startswith(b"PK") and zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as z:
            names = set(z.namelist())
            if "META-INF/container.xml" in names:
                return "epub"
    raise BookError("Only PDF and EPUB files are supported")


def finalize(temp_name: str, fmt: str) -> str:
    """Rename the temporary upload to its final stored name."""
    final = f"{temp_name.rsplit('.', 1)[0]}.{fmt}"
    path_for(temp_name).rename(path_for(final))
    return final


def _clean(value) -> str:
    return " ".join(str(value or "").split())[:300]


def pdf_metadata(path: Path) -> dict:
    try:
        reader = PdfReader(str(path))
        if reader.is_encrypted and not reader.decrypt(""):
            raise BookError("This PDF is password protected. Upload an unlocked copy.")
        info = reader.metadata or {}
        return {"pages": len(reader.pages), "title": _clean(info.get("/Title")), "author": _clean(info.get("/Author")),
                "description": _clean(info.get("/Subject")), "cover": None}
    except BookError:
        raise
    except Exception as e:
        raise BookError("This PDF couldn't be read. It may be damaged.") from e


def _read_small(z: zipfile.ZipFile, name: str, limit: int) -> bytes | None:
    try:
        info = z.getinfo(name)
    except KeyError:
        return None
    if info.file_size > limit:
        return None
    return z.read(info)


def epub_metadata(path: Path) -> dict:
    """Title, author, description and cover image from the EPUB package document."""
    try:
        with zipfile.ZipFile(path) as z:
            container = _read_small(z, "META-INF/container.xml", MAX_XML)
            root = ElementTree.fromstring(container or b"")
            rootfile = root.find(".//c:rootfile", NS)
            opf_path = rootfile.get("full-path") if rootfile is not None else None
            opf_bytes = _read_small(z, opf_path, MAX_XML) if opf_path else None
            if not opf_bytes:
                raise BookError("This EPUB has no package document, so it can't be opened.")
            opf = ElementTree.fromstring(opf_bytes)
            meta = opf.find("opf:metadata", NS)

            def dc(tag):
                el = meta.find(f"dc:{tag}", NS) if meta is not None else None
                return _clean("".join(el.itertext())) if el is not None else ""

            manifest = {item.get("id"): item for item in opf.iterfind("opf:manifest/opf:item", NS)}
            cover_item = next((i for i in manifest.values() if "cover-image" in (i.get("properties") or "")), None)
            if cover_item is None and meta is not None:
                ref = next((m.get("content") for m in meta.iterfind("opf:meta", NS) if m.get("name") == "cover"), None)
                cover_item = manifest.get(ref)
            cover = None
            if cover_item is not None and (cover_item.get("media-type") or "") in COVER_TYPES:
                href = posixpath.normpath(posixpath.join(posixpath.dirname(opf_path), cover_item.get("href", "")))
                data = _read_small(z, href, MAX_COVER)
                if data:
                    cover = (data, COVER_TYPES[cover_item.get("media-type")])
            description = dc("description")
            if "<" in description:  # descriptions are often HTML
                try:
                    description = _clean("".join(ElementTree.fromstring(f"<d>{description}</d>").itertext()))
                except ElementTree.ParseError:
                    pass
            return {"pages": None, "title": dc("title"), "author": dc("creator"), "description": description[:2000],
                    "cover": cover}
    except BookError:
        raise
    except (zipfile.BadZipFile, ElementTree.ParseError, KeyError, ValueError) as e:
        raise BookError("This EPUB couldn't be read. It may be damaged.") from e


def cover_extension(data: bytes) -> str:
    for magic, ext in COVER_MAGIC:
        if data.startswith(magic):
            return ext
    raise BookError("The cover must be a JPG, PNG, WebP or GIF image")


def save_cover(data: bytes, ext: str) -> str:
    if len(data) > MAX_COVER:
        raise BookError("The cover image must be under 5 MB")
    name = f"{secrets.token_hex(12)}.cover.{ext}"
    path_for(name).write_bytes(data)
    return name


async def read_cover(upload: UploadFile) -> bytes:
    data = await upload.read(MAX_COVER + 1)
    if len(data) > MAX_COVER:
        raise BookError("The cover image must be under 5 MB")
    return data


def media_type(name: str) -> str:
    ext = name.rsplit(".", 1)[-1].lower()
    return {"pdf": "application/pdf", "epub": "application/epub+zip", "jpg": "image/jpeg", "png": "image/png",
            "webp": "image/webp", "gif": "image/gif"}.get(ext, "application/octet-stream")


def title_from_filename(name: str) -> str:
    stem = Path(name or "Untitled").stem
    return _clean(stem.replace("_", " ").replace("-", " ")) or "Untitled"

